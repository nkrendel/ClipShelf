import AppKit

/// Reads clips from, and writes clips back to, an NSPasteboard.
enum PasteboardIO {
    /// Marker types from nspasteboard.org that apps (mostly password managers)
    /// set when a copy should not be recorded by clipboard managers.
    static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Added by macOS when Universal Clipboard delivers a copy made on another device.
    static let remoteClipboardType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

    /// Largest image or PDF kept in history, to keep the history file small.
    static let maxBinaryBytes = 20 * 1024 * 1024

    static func readClip(from pasteboard: NSPasteboard, storing store: StoreTypes, now: Date = Date()) -> Clip? {
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: skipTypes) else { return nil }

        var fileURLs: [URL]?
        var url: URL?
        var text: String?
        var rtf: Data?
        var rtfd: Data?
        var pdf: Data?
        var image: Data?

        if store.files {
            let urls = pasteboard.readObjects(
                forClasses: [NSURL.self],
                options: [.urlReadingFileURLsOnly: true]
            ) as? [URL]
            if let urls, !urls.isEmpty { fileURLs = urls }
        }
        if store.urls, fileURLs == nil {
            let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL]
            url = urls?.first { !$0.isFileURL }
        }
        if store.text {
            text = pasteboard.string(forType: .string)
        }
        if store.richText {
            rtf = pasteboard.data(forType: .rtf)
            rtfd = pasteboard.data(forType: .rtfd)
        }
        if store.pdf, let data = pasteboard.data(forType: .pdf), data.count <= maxBinaryBytes {
            pdf = data
        }
        if store.images, fileURLs == nil, types.contains(.png) || types.contains(.tiff) {
            if let png = pasteboard.data(forType: .png) {
                image = png
            } else if let tiff = pasteboard.data(forType: .tiff),
                      let rep = NSBitmapImageRep(data: tiff) {
                image = rep.representation(using: .png, properties: [:])
            }
            if let data = image, data.count > maxBinaryBytes { image = nil }
        }

        let clip = Clip(
            text: text,
            rtf: rtf,
            rtfd: rtfd,
            pdf: pdf,
            fileURLs: fileURLs,
            url: url,
            image: image,
            created: now,
            fromOtherDevice: types.contains(remoteClipboardType)
        )
        return clip.isEmpty ? nil : clip
    }

    /// Puts a clip back on the pasteboard. With `plainText`, only the text is written.
    static func write(_ clip: Clip, to pasteboard: NSPasteboard, plainText: Bool = false) {
        pasteboard.clearContents()

        if plainText {
            let string = clip.text ?? clip.url?.absoluteString
                ?? clip.fileURLs?.map(\.path).joined(separator: "\n")
            if let string { pasteboard.setString(string, forType: .string) }
            return
        }

        if let fileURLs = clip.fileURLs, !fileURLs.isEmpty {
            pasteboard.writeObjects(fileURLs as [NSURL])
            return
        }

        let item = NSPasteboardItem()
        if let text = clip.text { item.setString(text, forType: .string) }
        if let rtf = clip.rtf { item.setData(rtf, forType: .rtf) }
        if let rtfd = clip.rtfd { item.setData(rtfd, forType: .rtfd) }
        if let pdf = clip.pdf { item.setData(pdf, forType: .pdf) }
        if let image = clip.image {
            item.setData(image, forType: .png)
            if let tiff = NSImage(data: image)?.tiffRepresentation {
                item.setData(tiff, forType: .tiff)
            }
        }
        if let url = clip.url {
            item.setString(url.absoluteString, forType: .URL)
            if clip.text == nil { item.setString(url.absoluteString, forType: .string) }
        }
        pasteboard.writeObjects([item])
    }
}
